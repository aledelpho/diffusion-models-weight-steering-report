"""Build docs/ROADMAP_MASTER.md (inventory + queue) and roadmap.html from docs/roadmap_items.csv and the results pages.
Written 2026-10-18 after an earlier roadmap cited pages and files that do not exist. Every path in the items file
and every results page linked is checked: the build fails if one is missing.

  python experiments/build_roadmap.py           # writes both files
  python experiments/build_roadmap.py --check   # fails if they are out of date
"""
import argparse, csv, html, json, re, sys
from pathlib import Path
import yaml
ROOT = Path(__file__).resolve().parent.parent
ITEMS = ROOT / "docs" / "roadmap_items.csv"
MD = ROOT / "docs" / "ROADMAP_MASTER.md"
HTML = ROOT / "roadmap.html"
ORDER = ["in progress", "waiting for decision", "open", "proposed", "done", "withdrawn"]


def items():
    rows = list(csv.DictReader(open(ITEMS, encoding="utf-8")))
    missing = [(r["id"], f) for r in rows for f in r["files"].split(";") if f and not (ROOT / f).exists()]
    if missing:
        sys.exit(f"missing files cited in roadmap_items.csv: {missing}")
    bad = [r["id"] for r in rows if r["status"] not in ORDER]
    if bad:
        sys.exit(f"unknown status in {bad}")
    return rows


def pages():
    out = []
    for p in sorted((ROOT / "results").glob("[0-9][0-9]-*.md")):
        fm = yaml.safe_load(p.read_text(encoding="utf-8").split("---", 2)[1])
        st = {}
        for c in fm.get("claims") or []:
            st[c["status"]] = st.get(c["status"], 0) + 1
        out.append({"page": p.name, "title": fm.get("title", ""), "status": fm.get("status", ""),
                    "renders": (fm.get("corpus") or {}).get("renders", ""), "claims": st})
    return out


def build_md(rows, pg):
    L = ["# Roadmap — state of the project and what comes next", "",
         "Generated by `experiments/build_roadmap.py` from `docs/roadmap_items.csv` and the front matter of `results/`. "
         "Edit the CSV, not this file. The build checks that every file cited exists.", "",
         "## Rules for every agent (Claude, Antigravity, Argon, others)", "",
         "* A pre-registration is committed **before** the first render it covers; otherwise the result is exploratory.",
         "* Every file or page a document cites must exist. Run `python experiments/build_roadmap.py --check` and "
         "`python experiments/validate_notebook.py --dir results` before handing over.",
         "* Claim statuses on the results pages change only with Alessandro's approval.",
         "* A blind human rule is not replaced by automatic metrics, and correlations are not written as causes.",
         "* Never use `monitor_and_shutdown.py`; never close, shut down or change system settings; no push without the "
         "publication directive.", "",
         "## Results pages (from their front matter)", "",
         "| page | title | page status | renders | claims |", "|---|---|---|---|---|"]
    for p in pg:
        cl = ", ".join(f"{k} {v}" for k, v in sorted(p["claims"].items()))
        L.append(f"| [{p['page'][:2]}](../results/{p['page']}) | {p['title']} | {p['status']} | {p['renders']} | {cl} |")
    for st in ORDER:
        sel = sorted([r for r in rows if r["status"] == st], key=lambda r: (r["priority"] or "9", r["id"]))
        if not sel:
            continue
        L += ["", f"## {st.capitalize()}", "", "| id | area | priority | what | state | next | files |",
              "|---|---|---|---|---|---|---|"]
        for r in sel:
            files = "<br>".join(f"`{f}`" for f in r["files"].split(";") if f)
            L.append(f"| **{r['id']}** | {r['area']} | {r['priority']} | {r['title']} | {r['state']} | {r['next']} | {files} |")
    return "\n".join(L) + "\n"


