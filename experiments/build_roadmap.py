def build_html(rows, pg):
    return (PAGE.replace("__ITEMS__", json.dumps(rows, ensure_ascii=False)).replace("__PAGES__", json.dumps(pg, ensure_ascii=False))
            .replace("__ORDER__", json.dumps(ORDER)))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    rows, pg = items(), pages()
    md, ht = build_md(rows, pg), build_html(rows, pg)
    if a.check:
        ok = MD.read_text(encoding="utf-8") == md and HTML.read_text(encoding="utf-8") == ht
        print("roadmap", "up to date" if ok else "OUT OF DATE"); sys.exit(0 if ok else 1)
    MD.write_text(md, encoding="utf-8"); HTML.write_text(ht, encoding="utf-8")
    print(f"wrote {MD.name} and {HTML.name}: {len(rows)} items, {len(pg)} pages")
