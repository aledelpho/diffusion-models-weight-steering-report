"""MOSS-Image survey - read-only map of the checkpoints and of ComfyUI's code for the model, before any edit or render.
Written 2026-10-25. Reads only safetensors headers (no weights loaded, no GPU) and copies source files.

  python moss_survey.py     # data/moss_structure_*.csv, docs/moss_survey.md, docs/moss_source/*.py

For every checkpoint found (MOSS DiT SFT, the target, and Base if present, Qwen3.5-9B text encoder, FLUX.2 small VAE, and Krea-2's DiT and text
encoder for comparison): every tensor name with digits collapsed to '#', how many times the pattern repeats, shape and
dtype of the first instance; the number of blocks per prefix. Then every ComfyUI source file that mentions MOSS.
"""
import csv, json, re, shutil, struct, sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODEL_DIRS = [Path(r"D:\StabilityMatrix-win-x64\Data\Models"), Path(r"C:\StabilityMatrix-win-x64\Data\Models")]
COMFY = [Path(r"D:\StabilityMatrix-win-x64\Data\Packages\ComfyUI"), Path(r"C:\StabilityMatrix-win-x64\Data\Packages\ComfyUI")]
WANT = {"moss_dit": "moss_image_sft*.safetensors",          # the SFT checkpoint is the one we will edit (2026-10-25)
        "moss_dit_base": "moss_image_base*.safetensors",     # reported if present, for comparison only
        "moss_te": "qwen3.5_9b*.safetensors", "moss_vae": "flux2-vae*.safetensors",
        "krea2_dit": "krea2_turbo*.safetensors", "krea2_te": "qwen3vl_4b*.safetensors"}


def header(p):
    with open(p, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        return json.loads(f.read(n))


def find(pattern):
    out = []
    for d in MODEL_DIRS:
        if d.exists():
            out += sorted(d.rglob(pattern))
    return out


def summarise(tag, p):
    h = header(p); meta = h.pop("__metadata__", {})
    pat = OrderedDict()
    for k, v in h.items():
        g = re.sub(r"\.\d+\.", ".#.", "." + k + ".")[1:-1]
        e = pat.setdefault(g, {"pattern": g, "count": 0, "shape": "x".join(map(str, v["shape"])), "dtype": v["dtype"], "idx": set()})
        e["count"] += 1
        for m in re.finditer(r"\.(\d+)\.", "." + k + "."):
            e["idx"].add(int(m.group(1)))
    rows = [{"pattern": e["pattern"], "count": e["count"], "shape": e["shape"], "dtype": e["dtype"],
             "max_index": max(e["idx"]) if e["idx"] else ""} for e in pat.values()]
    out = ROOT / "data" / f"moss_structure_{tag}_{p.stem}.csv"
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    dtypes = {}
    for v in h.values():
        dtypes[v["dtype"]] = dtypes.get(v["dtype"], 0) + 1
    prefixes = {}
    for k in h:
        m = re.match(r"(.*?)\.(\d+)\.", k)
        if m:
            prefixes.setdefault(m.group(1), set()).add(int(m.group(2)))
    return {"file": str(p), "size_GB": round(p.stat().st_size / 1e9, 2), "tensors": len(h), "patterns": len(rows),
            "dtypes": dtypes, "blocks": {k: len(v) for k, v in sorted(prefixes.items())}, "metadata_keys": list(meta)[:20], "csv": out.name}


def main():
    lines = ["# MOSS-Image survey (read-only)", "", "Generated by `experiments/moss_survey.py`. Headers only; no weight was loaded.", ""]
    for tag, pat in WANT.items():
        files = find(pat)
        lines.append(f"## {tag} — `{pat}`")
        if not files:
            lines += ["", "NOT FOUND", ""]; continue
        for p in files:
            s = summarise(tag, p)
            lines += ["", "```json", json.dumps(s, indent=1), "```", ""]
            print(tag, p.name, s["tensors"], "tensors", s["dtypes"])
    src_out = ROOT / "docs" / "moss_source"; src_out.mkdir(exist_ok=True)
    lines.append("## ComfyUI source files that mention MOSS")
    for c in COMFY:
        if not c.exists():
            continue
        for f in list((c / "comfy").rglob("*.py")) + list((c / "comfy_extras").rglob("*.py")):
            try:
                t = f.read_text(encoding="utf-8", errors="ignore")
            except Exception:
                continue
            if re.search(r"moss", t, re.I):
                dst = src_out / (f.relative_to(c).as_posix().replace("/", "__"))
                shutil.copyfile(f, dst); lines.append(f"* `{f.relative_to(c).as_posix()}` -> `docs/moss_source/{dst.name}`")
                print("source", f.relative_to(c))
        break
    (ROOT / "docs" / "moss_survey.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/moss_survey.md")


if __name__ == "__main__":
    main()
