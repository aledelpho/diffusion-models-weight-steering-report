"""Write results/PROMPTS.md: every prompt the results pages rest on, once, in full (2026-10-15).

A reader could not find the prompts: they live in the plan CSVs cited in each page's "Reproducing this" block, one
row per render. This script reads every CSV a results page cites, keeps the ones with a prompt column, and lists
each distinct prompt text once, with its id, its seeds and the file it comes from. Nothing is typed by hand.

  python experiments/build_prompts_page.py           # writes results/PROMPTS.md
  python experiments/build_prompts_page.py --check   # fails if PROMPTS.md is out of date
"""
import argparse, csv, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUT = RESULTS / "PROMPTS.md"
TEXT_COLS = ("prompt_text", "prompt")
ID_COLS = ("prompt_id", "char", "prompt_key", "prompt_tag")
SEED_COLS = ("seed", "base_seed")
csv.field_size_limit(10 ** 8)


def title(page):
    m = re.search(r'^title:\s*"?(.*?)"?\s*$', page.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else page.stem


def prompts_of(path):
    with open(path, encoding="utf-8-sig", newline="") as f:
        rd = csv.DictReader(f)
        cols = rd.fieldnames or []
        tcol = next((c for c in TEXT_COLS if c in cols), None)
        if not tcol:
            return None
        icol = next((c for c in ID_COLS if c in cols), None)
        scol = next((c for c in SEED_COLS if c in cols), None)
        seen = {}
        for r in rd:
            t = (r[tcol] or "").strip()
            if not t or " " not in t:   # measure files have a 'prompt' column holding only an id
                continue
            e = seen.setdefault(t, {"ids": [], "seeds": []})
            i = r.get(icol, "") if icol else ""
            if i and i not in e["ids"]:
                e["ids"].append(i)
            s = r.get(scol, "") if scol else ""
            if s and s not in e["seeds"]:
                e["seeds"].append(s)
        return seen or None


def build():
    lines = ["# The prompts", "",
             "Every prompt the results pages rest on, listed once and in full. They are read from the data files each "
             "page cites in its *Reproducing this* block (one row per render there); this page is generated by "
             "`experiments/build_prompts_page.py`, nothing is typed by hand. Ids are the short names used on the pages.",
             "", "Sampling for all of them, unless a page says otherwise: Krea-2 turbo bf16, euler_ancestral, simple "
             "scheduler, 9 steps, cfg 1.0, 1024×1280.", ""]
    total = set(); missing = []; first = {}; anchor = {}
    for page in sorted(RESULTS.glob("[0-9][0-9]-*.md")):
        cited = sorted(set(re.findall(r"data/[\w./-]+\.csv", page.read_text(encoding="utf-8"))))
        blocks = []
        for d in cited:
            p = ROOT / d
            if not p.exists():
                continue
            got = prompts_of(p)
            if got:
                blocks.append((d, got))
        if not blocks:
            missing.append(page.name); continue
        anchor[page.name] = "p" + page.name[:2]
        lines += [f'<a id="p{page.name[:2]}"></a>', "", f"## {page.name[:2]} · [{title(page)}]({page.name})", ""]
        done = set(); reused = []
        for d, got in blocks:
            new = {t: e for t, e in got.items() if t not in done and t not in first}
            for t, e in got.items():
                if t in first and t not in done:
                    done.add(t); reused.append((first[t], ", ".join(e["ids"][:3]) or "prompt"))
            if not new:
                continue
            lines += [f"From `{d}`:", ""]
            for t, e in new.items():
                done.add(t); total.add(t); first[t] = page.name
                ids = ", ".join(e["ids"][:6]) + (" …" if len(e["ids"]) > 6 else "")
                seeds = ", ".join(e["seeds"][:8]) + (" …" if len(e["seeds"]) > 8 else "")
                head = f"**{ids or 'prompt'}**" + (f" · seeds {seeds}" if seeds else "")
                lines += [head, "", "```text", t, "```", ""]
        if reused:
            by = {}
            for pg, i in reused:
                by.setdefault(pg, set()).add(i)
            for pg, ids in sorted(by.items()):
                lines += [f"Also used on this page, full text under [{pg[:2]}](#{anchor[pg]}): {'; '.join(sorted(ids))}.", ""]
    lines += ["---", "", f"{len(total)} distinct prompts."]
    if missing:
        lines += ["", "Pages that cite no file with prompt texts: " + ", ".join(missing) + "."]
    return "\n".join(lines) + "\n", len(total), missing


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    text, n, missing = build()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("PROMPTS.md", "up to date" if ok else "OUT OF DATE"); sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} distinct prompts; pages without prompt files: {missing}")
